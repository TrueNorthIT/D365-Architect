using System.Text.Json.Nodes;
using System.Xml.Linq;
using D365Architect.Tests.TestSupport;
using Xunit;

namespace D365Architect.Tests.Services.Schema;

/// <summary>
/// Issue #21 (security role privileges as YAML), build wiring: the repo has no hook for "a build regenerated the schemas" other than the
/// project file, so these read the <c>RegenerateSchemas</c> target in <c>D365 Architect/D365 Architect.csproj</c> and the committed
/// <c>schema/*.schema.json</c> files.
/// REQ-22: "Every ordinary build regenerates `schema/security.schema.json` and `schema/role.schema.json` (add to `RegenerateSchemas`); committed in this PR."
/// REQ-23: "The build also regenerates `choice.schema.json` (currently missing from `RegenerateSchemas`)."
/// Tagged with the "Feature" trait "security-roles-yaml".
/// </summary>
[Trait("Feature", "security-roles-yaml")]
public sealed class SchemaBuildWiringTests
{
    private static List<string> RegenerateSchemasCommands()
    {
        var project = XDocument.Load(Path.Combine(RepositoryRoot.Path, "D365 Architect", "D365 Architect.csproj"));
        var target = project.Descendants("Target").SingleOrDefault(t => (string?)t.Attribute("Name") == "RegenerateSchemas");
        Assert.True(target is not null, "the project file should have a RegenerateSchemas target (AfterTargets=Build) that regenerates schema/*.schema.json.");
        return target!.Elements("Exec").Select(e => (string?)e.Attribute("Command") ?? "").ToList();
    }

    // REQ-22 / REQ-23: one `schema export --for <type>` per file type, so an ordinary build regenerates it.
    // Code path: the RegenerateSchemas target in D365 Architect.csproj.
    [Theory]
    [Trait("Requirement", "REQ-22")]
    [InlineData("security", "REQ-22")]
    [InlineData("role", "REQ-22")]
    [InlineData("choice", "REQ-23")]
    [InlineData("table", "REQ-22")]
    [InlineData("view", "REQ-22")]
    [InlineData("form", "REQ-22")]
    public void RegenerateSchemas_RunsSchemaExportForEachFileType(string assetType, string requirement)
    {
        var commands = RegenerateSchemasCommands();

        Expect.True(commands.Any(c => c.Contains($"schema export --for {assetType}", StringComparison.Ordinal)),
            $"{requirement}: the RegenerateSchemas target should run 'schema export --for {assetType}' so every build regenerates schema/{assetType}.schema.json. Commands: <{string.Join(" | ", commands)}>.");
    }

    // REQ-22: "committed in this PR": the generated schema files exist in the repo's schema folder.
    [Theory]
    [Trait("Requirement", "REQ-22")]
    [InlineData("security.schema.json", "object")]
    [InlineData("role.schema.json", "object")]
    [InlineData("choice.schema.json", "array")]
    public void CommittedSchemaFile_Exists(string fileName, string rootType)
    {
        var path = Path.Combine(RepositoryRoot.Path, "schema", fileName);

        Expect.True(File.Exists(path), $"REQ-22/REQ-23: '{path}' should be committed (generated by a build).");
        Expect.Equal(rootType, (string)JsonNode.Parse(File.ReadAllText(path))!["type"]!, $"'{fileName}' should be a JSON Schema whose YAML root is a {rootType}.");
    }
}
